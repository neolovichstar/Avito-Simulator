function questsBlock(): string {
  const kinds = [...new Set(QUEST_POOL.map((q) => q.kind))]
  const top = [...QUEST_POOL].sort((a, b) => b.reward - a.reward).slice(0, 5)
  return [
    `Виды квестов: ${kinds.join(', ')}. Всего ${QUEST_POOL.length} разных квестов, каждый день выдаётся новый набор.`,
    `Самые жирные: ${top.map((q) => `«${q.title}» (${rub(q.reward)})`).join(', ')}.`,
    `Достижений: ${ACHIEVEMENTS.length}.`,
  ].join('\n')
}

