export function supportFallbackReply(userText: string): string {
  const t = userText.toLowerCase()
  for (const p of FALLBACK_PAIRS) {
    if (p.keys.some((k) => t.includes(k))) return p.text
  }
  const generic = [
    'Принял, спасибо. Передал вопрос админам, ответ придёт сюда же в чат 🙂',
    'Смотри, что могу подсказать сразу: деньги и операции в Банке, налоги в «Налогах», покупки за звёзды в «Настройках» → «Магазин». Если не то, уточни вопрос.',
    'Записал, разберёмся. Если можешь, кинь пару деталей: что делал и что вышло.',
  ]
  return generic[Math.floor(Math.random() * generic.length)]
}
