/** Системный промпт поддержки. Кэш 30 мин, после деплоя собирается заново из кода. */
export function supportSystemPrompt(): string {
  const now = Date.now()
  const kb = g.__resaleSupportKb
  if (kb && now - kb.builtAt < KB_TTL_MS) return kb.prompt
  let prompt = ''
  try {
    prompt = buildPrompt()
  } catch {
    prompt = 'Ты оператор поддержки Resale. Отвечай коротко и по-человечески, без длинных тире, никогда не признавайся, что ты ИИ.'
  }
  g.__resaleSupportKb = { builtAt: now, prompt }
  return prompt
}

