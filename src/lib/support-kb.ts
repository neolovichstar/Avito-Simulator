function rub(n: number): string {
  return `${Math.round(n).toLocaleString('ru-RU')} ₽`
}

function catalogBlock(): string {
  const byCat = new Map<string, { count: number; min: number; max: number; sum: number; samples: string[] }>()
  for (const it of CATALOG) {
    const b = byCat.get(it.category) ?? { count: 0, min: Infinity, max: 0, sum: 0, samples: [] }
    b.count++
    b.min = Math.min(b.min, it.basePrice)
    b.max = Math.max(b.max, it.basePrice)
    b.sum += it.basePrice
    if (b.samples.length < 4) b.samples.push(it.title)
    byCat.set(it.category, b)
  }
  const lines: string[] = []
  for (const [cat, b] of byCat) {
    const label = CATEGORY_LABEL[cat] ?? cat
    lines.push(`- ${label}: ${b.count} видов, цены примерно от ${rub(b.min)} до ${rub(b.max)} (средняя ${rub(b.sum / b.count)}); например: ${b.samples.join(', ')}`)
  }
  return lines.join('\n')
}

